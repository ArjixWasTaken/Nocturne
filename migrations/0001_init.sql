CREATE TABLE IF NOT EXISTS images (model TEXT NOT NULL, size INTEGER NOT NULL, image BLOB NOT NULL, UNIQUE(model, size));
CREATE TABLE IF NOT EXISTS playlist_resume (id TEXT PRIMARY KEY, song_id TEXT NOT NULL, timestamp REAL DEFAULT 0);
CREATE TABLE IF NOT EXISTS playback_scrobble (month TEXT NOT NULL, song_id TEXT NOT NULL, amount INTEGER DEFAULT 0, UNIQUE(month, song_id));
CREATE TABLE IF NOT EXISTS lyrics (id TEXT PRIMARY KEY, type TEXT NOT NULL, content TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS stars (id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS ratings (id TEXT PRIMARY KEY, rating INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS radios (id TEXT PRIMARY KEY, name TEXT NOT NULL, stream_url TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS scrobble (id TEXT PRIMARY KEY, plays INTEGER DEFAULT 0, last_play REAL DEFAULT 0, album_id TEXT, artist_id TEXT);
